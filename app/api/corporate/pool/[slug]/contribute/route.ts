import { NextRequest, NextResponse } from "next/server";
import { createClient } from "@supabase/supabase-js";
import { z } from "zod";

const supabase = createClient(
  process.env.NEXT_PUBLIC_SUPABASE_URL!,
  process.env.SUPABASE_SERVICE_ROLE_KEY!
);

const contributeSchema = z.object({
  name: z.string().min(1).max(100),
  phone: z.string().min(1).max(20),
  amount: z.coerce.number().positive(),
  message: z.string().max(500).optional(),
  isAnonymous: z.boolean().default(false),
});

type PoolRow = {
  id: string;
  slug: string;
  status: string;
  min_contribution: number;
  target_amount: number;
  current_balance: number;
  deadline: string;
  anonymous_contributions: boolean;
  contributor_count: number;
};

const normalizePhone = (raw: string) => {
  const d = raw.replace(/\D/g, "");
  if (d.startsWith("0")) return `254${d.slice(1)}`;
  if (d.startsWith("254")) return d;
  return d;
};

/**
 * POST /api/corporate/pool/[slug]/contribute
 *
 * A public pool lives at /corporate/pool/[slug], not /pool/[slug]: the consumer
 * pool page reads `group_gifting_pools`, a different table with no shared ids or
 * slugs. Every corporate share link generated by POST /api/corporate/pools
 * pointed at it and resolved to a 404 — or worse, to somebody else's pool if a
 * slug ever collided.
 *
 * The pool is public by design (that is the point of a gift pool), so the slug
 * is the capability. Money is never taken here: a contribution is recorded as
 * unverified and the company match / payout happens once ops confirms the
 * transfer. Taking an unverified M-Pesa payment from a public form is how a
 * business ends up owing refunds it never authorised.
 */
export async function POST(
  req: NextRequest,
  { params }: { params: Promise<{ slug: string }> }
) {
  try {
    return await handle(req, params);
  } catch (e) {
    console.error("[corporate/pool] contribute threw:", e);
    return NextResponse.json({ error: "Could not record your contribution" }, { status: 500 });
  }
}

async function handle(
  req: NextRequest,
  params: Promise<{ slug: string }>
) {
  const parsed = contributeSchema.safeParse(await req.json().catch(() => null));
  if (!parsed.success) {
    return NextResponse.json(
      { error: parsed.error.issues[0]?.message ?? "Invalid contribution" },
      { status: 400 }
    );
  }

  const { slug } = await params;

  const { data: pool, error } = await supabase
    .from("corporate_gift_pools")
    .select(
      /* slug is needed for the payment reference the contributor is given —
         it is not on the page URL alone, because the buyer may be reading it
         from an email later. */
      "id, slug, status, min_contribution, target_amount, current_balance, " +
        "deadline, anonymous_contributions, contributor_count"
    )
    .eq("slug", slug)
    .maybeSingle<PoolRow>();

  if (error) {
    console.error("[corporate/pool] lookup failed:", error.message);
    return NextResponse.json({ error: "Could not load this pool" }, { status: 500 });
  }
  if (!pool) {
    return NextResponse.json({ error: "This pool is no longer available" }, { status: 404 });
  }

  if (pool.status !== "active") {
    return NextResponse.json({ error: "This pool is closed" }, { status: 409 });
  }
  if (new Date(pool.deadline).getTime() < Date.now()) {
    return NextResponse.json({ error: "This pool has closed" }, { status: 409 });
  }

  const amount = Number(parsed.data.amount);
  const minimum = Number(pool.min_contribution ?? 0);
  if (minimum && amount < minimum) {
    return NextResponse.json(
      { error: `The minimum contribution is KES ${Math.round(minimum).toLocaleString("en-KE")}` },
      { status: 400 }
    );
  }

  const target = Number(pool.target_amount ?? 0);
  const remaining = target - Number(pool.current_balance ?? 0);
  if (target > 0 && remaining > 0 && amount > remaining) {
    return NextResponse.json(
      {
        error:
          remaining <= 0
            ? "This pool is already fully funded"
            : `Only KES ${Math.round(remaining).toLocaleString("en-KE")} is still needed`,
      },
      { status: 400 }
    );
  }

  const { data: contribution, error: insertErr } = await supabase
    .from("corporate_pool_contributions")
    .insert({
      pool_id: pool.id,
      contributor_name: parsed.data.name,
      contributor_phone: normalizePhone(parsed.data.phone),
      amount,
      message: parsed.data.message ?? null,
      is_anonymous: parsed.data.isAnonymous,
      // Recorded, not taken. Ops confirms the transfer and flips this.
      is_verified: false,
      payment_method: "mpesa",
    })
    .select("id, amount, created_at")
    .single();

  if (insertErr) {
    console.error("[corporate/pool] contribution failed:", insertErr.message);
    return NextResponse.json(
      { error: "Could not record your contribution. Please try again." },
      { status: 500 }
    );
  }

  /* A contribution is recorded immediately but the balance only moves when ops
     verifies it — otherwise the progress bar is a claim the business has not
     confirmed, and a pool can look funded by money that never arrived. */
  return NextResponse.json({
    contribution,
    pendingVerification: true,
    message:
      "Recorded. Send your M-Pesa transfer using the pool reference and we will confirm it shortly.",
    reference: pool.slug.toUpperCase(),
  });
}
